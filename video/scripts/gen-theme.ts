// The face SVG's drawn bounds (eyes and smile) in its own units, read from the SVG so a redrawn face still lines up
const svg = readFileSync(join(kit, '02_Face_Mark/Rabik_face_ink.svg'), 'utf8');
const eyes = [...svg.matchAll(/<rect id="eye-\w+" x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)"/g)].map(m => m.slice(1).map(Number));
const smileY = [...svg.match(/id="smile" points="([^"]+)"/)![1].matchAll(/[\d.]+,([\d.]+)/g)].map(m => +m[1]);
const svgBox = { x: Math.min(...eyes.map(e => e[0])), y: Math.min(...eyes.map(e => e[1])), r: Math.max(...eyes.map(e => e[0] + e[2])), b: Math.max(...smileY, ...eyes.map(e => e[1] + e[3])) };

// Each image's face, found by its ink pixels above the wordmark, then painted out with the squircle's own shading
// (per column, between the colors just above and below), so <Face> can draw it again and animate it.
async function faceless(file: string, iconPart: number) {
  const { data, info } = await sharp(join(BRAND, file)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const W = info.width, H = info.height, limit = Math.floor(H * iconPart);
  const ink = (x: number, y: number) => { const i = (y * W + x) * 4; return data[i + 3] > 200 && data[i] < 120 && data[i + 1] < 120 && data[i + 2] < 120; };
  let x0 = W, y0 = H, x1 = 0, y1 = 0;
  for (let y = 0; y < limit; y++) for (let x = 0; x < W; x++) if (ink(x, y)) { x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y); }
  const pad = Math.ceil((x1 - x0) * 0.05) + 2;   // the antialiased rim and soft shading around each shape
  const mask = new Uint8Array(W * H);
  for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) if (ink(x, y))
    for (let dy = -pad; dy <= pad; dy++) for (let dx = -pad; dx <= pad; dx++) if (dx * dx + dy * dy <= pad * pad) mask[(y + dy) * W + x + dx] = 1;
  for (let x = x0 - pad; x <= x1 + pad; x++) for (let y = y0 - pad; y <= y1 + pad; y++) {
    if (!mask[y * W + x]) continue;
    let end = y; while (mask[(end + 1) * W + x]) end++;
    const a = ((y - 1) * W + x) * 4, b = ((end + 1) * W + x) * 4;
    for (let k = y; k <= end; k++) { const t = (k - y + 1) / (end - y + 2), i = (k * W + x) * 4; for (let c = 0; c < 4; c++) data[i + c] = Math.round(data[a + c] * (1 - t) + data[b + c] * t); }
    y = end;
  }
  const out = file.replace('.png', '_faceless.png');
  await sharp(data, { raw: { width: W, height: H, channels: 4 } }).png().toFile(join(BRAND, out));
  const scale = (x1 + 1 - x0) / (svgBox.r - svgBox.x);   // image px per SVG unit
  return { src: `brand/${out}`, original: `brand/${file}`, size: [W, H], face: { x: x0 - svgBox.x * scale, y: y0 - svgBox.y * scale, scale } };
}
const brandImages = { icon: await faceless('Rabik_icon_1024.png', 1), stacked: await faceless('Rabik_stacked_ink_transparent.png', 0.62) };
writeFileSync(join(VIDEO, 'src/theme.ts'), readFileSync(join(VIDEO, 'src/theme.ts'), 'utf8') +
  `// Where the face sits in each brand image (image px; face = the SVG's origin and px per SVG unit), from scripts/gen-theme.ts
export const brandImages = ${JSON.stringify(brandImages, null, 2)} as const;
export const faceSvg = ${JSON.stringify({ width: 464, height: 240, eyes: eyes.map(([x, y, w, h]) => ({ x, y, w, h })), smile: svg.match(/id="smile" points="([^"]+)"/)![1] })} as const;
`);
