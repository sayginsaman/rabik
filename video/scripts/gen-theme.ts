// Step 0: ui/brand first, else wherever rabik-brand-tokens.json lives under ui/
export function findBrandKit(): string {
  if (existsSync(join(REPO, 'ui/brand/05_Brand_Tokens/rabik-brand-tokens.json'))) return join(REPO, 'ui/brand');
  const walk = (dir: string): string | null => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, e.name);
      if (e.isDirectory()) { const hit = walk(p); if (hit) return hit; }
      else if (e.name === 'rabik-brand-tokens.json') return resolve(dirname(p), '..');
    }
    return null;
  };
  const kit = walk(join(REPO, 'ui'));
  if (!kit) throw new Error('Brand kit not found. Copy Rabik_Brand_Kit into ui/brand/ and run again.');
  return kit;
}

type Token = { name: string; value: string | { light: string; dark: string } };
const kit = findBrandKit();
const ds = JSON.parse(readFileSync(join(kit, '05_Brand_Tokens/rabik-design-system-tokens.json'), 'utf8'));
const brand = JSON.parse(readFileSync(join(kit, '05_Brand_Tokens/rabik-brand-tokens.json'), 'utf8'));

const camel = (s: string) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const light = (t: Token) => (typeof t.value === 'string' ? t.value : t.value.light).toUpperCase();
const colors: Record<string, string> = {};
for (const t of ds.color.tokens as Token[]) colors[camel(t.name)] = light(t);
// Brand-kit names the design system doesn't carry (Night, Graphite, Periwinkle Bright)
for (const [name, c] of Object.entries(brand.colors as Record<string, { hex: string }>)) {
  const key = camel(name.replace(/_/g, '-'));
  if (!Object.values(colors).includes(c.hex.toUpperCase()) || ['night', 'graphite'].includes(key)) colors[key] ??= c.hex.toUpperCase();
}
const radius = Object.fromEntries((ds.radius.tokens as { name: string; value: string }[]).map(t => [camel(t.name.replace('radius-', '')), parseFloat(t.value)]));
const space = Object.fromEntries((ds.spacing.tokens as { name: string; value: string }[]).map(t => [t.name.replace('space-', 's'), parseFloat(t.value)]));
const shadow = Object.fromEntries((ds.shadow.tokens as { name: string; value: string }[]).map(t => [camel(t.name.replace('shadow-', '')), t.value]));
const scene = JSON.parse(readFileSync(join(VIDEO, 'scene.v1.json'), 'utf8'));
const stack = (names: string[], generic: string) => [...names.map(n => (n.includes(' ') || n === 'Figtree' ? `"${n}"` : n)), generic].join(', ');
const fonts = {
  display: stack(scene.brand.fonts.display, 'sans-serif'),
  sans: stack(scene.brand.fonts.sans, 'sans-serif'),
  mono: stack(scene.brand.fonts.mono, 'monospace'),
};

writeFileSync(join(VIDEO, 'src/theme.ts'), `// Generated by scripts/gen-theme.ts from ${kit.replace(REPO + '/', '')}/05_Brand_Tokens. Do not edit: run npm run theme.
// Light-theme values; every color in the video comes from here or from scene.v1.json.
export const color = ${JSON.stringify(colors, null, 2)} as const;
export type ColorToken = keyof typeof color;
export const radius = ${JSON.stringify(radius)} as const;
export const space = ${JSON.stringify(space)} as const;
export const shadow = ${JSON.stringify(shadow)} as const;
export const font = ${JSON.stringify(fonts, null, 2)} as const;
export const typeScale = ${JSON.stringify(Object.fromEntries(ds.type.groups.flatMap((g: { styles: { name: string }[] }) => g.styles.map(s => [camel(s.name), s]))))} as const;
`);

